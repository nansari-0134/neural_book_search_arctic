# Step 4 ? embed the corpus (checkpointed) 
# ---------------------------------------------------------------------- 
def doc_text(m): 
    return " ".join([m["title"] or "", 
                      " ".join(m["popular_shelves"] or []), 
                      (m["description"] or "")[:900]]) 


def load_jina(device=None): 
    import torch 
    from sentence_transformers import SentenceTransformer 
    device = device or ("cuda" if torch.cuda.is_available() 
                       else "mps" if torch.backends.mps.is_available() else "cpu") 
    model = SentenceTransformer(MODEL_REPO, device=device, trust_remote_code=True, 
                               model_kwargs={"default_task": "retrieval"}) 
    print(f"jina loaded on {device}; prompts={list(model.prompts or {})}") 
    return model 


def embed_corpus(model, meta, book_ids): 
    """64K docs -> doc_embeddings.npy + doc_embedding_ids.json (chunked).""" 
    import numpy as np 
    if DOC_EMB.exists() and DOC_IDS.exists(): 
        ids = json.load(open(DOC_IDS)) 
        if ids == book_ids: 
            print("doc embeddings already cached") 
            return np.load(DOC_EMB) 
    texts = [doc_text(meta[b]) for b in book_ids] 
    CKPT_DIR.mkdir(exist_ok=True) 
    n_chunks = (len(book_ids) + DOC_CHUNK - 1) // DOC_CHUNK 
    start = len(list(CKPT_DIR.glob("emb_*.npy"))) 
    t0 = time.time() 
    for ci in range(start, n_chunks): 
        lo, hi = ci * DOC_CHUNK, min(len(book_ids), (ci + 1) * DOC_CHUNK) 
        e = model.encode(texts[lo:hi], batch_size=32, task="retrieval", 
                        prompt_name="document", convert_to_numpy=True, 
                        normalize_embeddings=True).astype("float32") 
        np.save(CKPT_DIR / f"emb_{ci:04d}.npy", e) 
        json.dump(book_ids[lo:hi], open(CKPT_DIR / f"ids_{ci:04d}.json", "w")) 
        rate = (time.time() - t0) / (hi - start * DOC_CHUNK) 
        print(f"doc chunk {ci}: {hi}/{len(book_ids)} " 
              f"ETA {(len(book_ids)-hi)*rate/60:.0f} min", flush=True) 
    embs = np.concatenate([np.load(CKPT_DIR / f"emb_{i:04d}.npy") 
                           for i in range(n_chunks)]) 
    np.save(DOC_EMB, embs) 
    json.dump(book_ids, open(DOC_IDS, "w")) 
    print(f"corpus embedded {embs.shape}") 
    return embs 


