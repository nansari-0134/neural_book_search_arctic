""" 
Full data-prep pipeline for the book semantic search project. 

Reproduces everything we did, end to end, from two inputs: 
 book_query_pairs.jsonl {book_id, title, queries[5]} (generated by Qwen3-8B) 
 goodreads_books.json.gz UCSD Goodreads dump 

Steps (each a function, run in order by main()): 
 1. audit_dataset() structural/diversity/leakage checks -> review CSV 
 2. join_metadata() join on book_id -> books_metadata.jsonl 
 3. make_sample() 500-book sample for LLM judging -> quality_sample_500.jsonl 
 4. embed_corpus() jina embeddings of all docs -> doc_embeddings.npy 
 5. build_training() work-cluster split + hard-negative mining -> training_data/ 

Optional: judge_sample() Phi-4 GGUF grading of the sample (needs llama-cpp). 

Run: python prepare_data.py # steps 1-5 
 python prepare_data.py --with-judge --gguf /path/phi-4-Q4_K_M.gguf 
""" 

